def create_random_pattern(pattern, min_idx, max_idx):
    for i in range(min_idx, max_idx + 1):
        pattern[i] = random.random()


def create_similar_random_pattern(pattern, ref_pattern, std, min_idx, max_idx):
    for i in range(min_idx, max_idx + 1):
        if ref_pattern[i] == -1:
            val = random.random()
        else:
            val = random_normal(ref_pattern[i], std)
            if val < 0:
                val = 0
            elif val > 1:
                val = 1
        pattern[i] = val


def create_overlapping_random_pattern(pattern, ref_pattern, pattern_size, p):
    global VERBOSE, param_itemDistractorNoise

    if VERBOSE:
        print(
            f"   Create a distractor sharing {int(p * 100)}% units with the item at previous position"
        )

    i = 1
    while i <= pattern_size and int(ref_pattern[i]) == -1:
        pattern[i] = -1
        i += 1

    first_used_unit = i

    num_neg = int((1 - p) * pattern_size / 4)
    for _ in range(num_neg):
        pattern[i] = -1
        i += 1

    create_similar_random_pattern(
        pattern,
        ref_pattern,
        param_itemDistractorNoise,
        i,
        i + pattern_size // 4
    )

    for c in range(first_used_unit + pattern_size // 4, first_used_unit, -1):
        alea = random.randrange(pattern_size // 4) + first_used_unit
        pattern[alea], pattern[c] = pattern[c], pattern[alea]

    for c in range(i + pattern_size // 4 + 1, pattern_size + 1):
        pattern[c] = -1


def rmse(v1, v2, size):
    total = 0.0
    for i in range(1, size + 1):
        diff = v1[i] - v2[i]
        total += diff * diff
    return math.sqrt(total / size)


def decay(item_position_matrix, factor, excluded_item):
    for i in range(1, MAX_ITEM + 1):
        if excluded_item == -1 or i != excluded_item:
            for j in range(1, nbPositionUnits + 1):
                if item_position_matrix[i][j] != 0:
                    item_position_matrix[i][j] *= factor


def interfere(old_item_vector, new_item_vector, p):
    for j in range(1, NB_ITEM_UNITS + 1):
        if (
            old_item_vector[j] != new_item_vector[j]
            and int(old_item_vector[j]) != -1
            and int(new_item_vector[j]) != -1
        ):
            old_item_vector[j] = old_item_vector[j] * (1 - p) + new_item_vector[j] * p


