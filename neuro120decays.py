def get_cognitive_load():
    if param_Ta + param_freeTime == 0:
        return 0.0
    load = param_Ta / (param_Ta + param_freeTime)
    return max(0.0, min(1.0, load))


def get_interference_history():
    raw = distractorNumber * param_itemDistractorOverlap / max(1, nbop * nbmemo)
    return max(0.0, min(1.0, raw))


def get_decay_rate():
    base = param_D

    if adaptive_mode == "fixed":
        return base

    elif adaptive_mode == "linear":
        load = get_cognitive_load()
        return base * (1.0 + adaptive_alpha * load)

    elif adaptive_mode == "threshold":
        load = get_cognitive_load()
        return adaptive_high_decay if load >= adaptive_threshold else adaptive_low_decay

    elif adaptive_mode == "interference":
        hist = get_interference_history()
        return base * (1.0 + adaptive_alpha * hist)

    elif adaptive_mode == "log":
        load = get_cognitive_load()
        return base * (1.0 + adaptive_alpha * math.log(1.0 + load))

    else:
        error("Unknown adaptive_mode:", adaptive_mode)


def apply_decay(item_position_matrix, duration, excluded_item):
    current_decay = get_decay_rate()
    decay_trace.append(current_decay)
    decay(item_position_matrix, math.exp(-current_decay * duration), excluded_item)


def retrieve(position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
             item_position_matrix, item_strength, pos, status):
    global var_tr, globalTime, VERBOSE

    if status == 0:
        var_r_local = random_normal(param_R, param_s)
        if var_r_local < 0.1:
            var_r_local = 0.1
        var_tr = logTauE / var_r_local
        if var_tr > presentationTime:
            var_tr = presentationTime

    retrieval_duration = var_tr
    activation_max = -99999.0
    best_wm_item = -1

    if VERBOSE:
        print(f"[{globalTime:.2f}s] ", end="")

    activation_values = [0.0] * (MAX_MEMORANDA + distractorNumber + 1)

    for item in range(1, MAX_MEMORANDA + distractorNumber + 1):
        total = 0.0

        for i in range(1, nbPositionUnits + 1):
            if position_vectors[pos][i] != 0:
                total += position_vectors[pos][i] * item_position_matrix[item][i]

        total += random_normal(0, 1) * max(param_sigma, 0.0001)

        if VERBOSE:
            activation_values[item] = total

        if total > activation_max:
            activation_max = total
            best_wm_item = item

    if VERBOSE:
        switch_to_distractors = False
        for item in range(1, MAX_MEMORANDA + distractorNumber + 1):
            if item > MAX_MEMORANDA and not switch_to_distractors:
                print("... ", end="")
                switch_to_distractors = True

            if item == best_wm_item:
                print(RED, end="")

            if item <= 26 and item <= MAX_MEMORANDA:
                print(f"{chr(item + ord('A') - 1)}:", end="")
                pr2(activation_values[item])
            elif item > MAX_MEMORANDA:
                print(f"{item - MAX_MEMORANDA}:", end="")
                pr2(activation_values[item])

            if item == best_wm_item:
                print(RESET, end="")
            print(" ", end="")
        print()

    if activation_max < param_theta:
        if VERBOSE:
            print("No memoranda are above the theta threshold.")
        return 0, activation_max, retrieval_duration, best_wm_item
    else:
        min_rmse = 99999.0
        retrieved_item = 0
        for item in range(1, MAX_MEMORANDA + distractorNumber + 1):
            a_rmse = rmse(item_vectors_in_wm[best_wm_item], item_vectors_in_ltm[item], NB_ITEM_UNITS)
            if a_rmse < min_rmse:
                min_rmse = a_rmse
                retrieved_item = item

        if VERBOSE:
            print(
                f"   {CYN}Pos{pos}: {name(retrieved_item)} ({activation_max:.2f}) is the closest LTM item "
                f"to the best WM item ({name(best_wm_item)}) (RMSE={min_rmse:.4f}){RESET}"
            )

        return retrieved_item, activation_max, retrieval_duration, best_wm_item


def encode(position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
           item_position_matrix, item_strength, initial_encoding,
           current_item, best_wm_item, position, time_left,
           strength_divisor, duration, distractor):
    global var_te, var_eta, var_tr, globalTime, distractorNumber

    if distractor:
        current_item_symbol = chr(current_item - MAX_MEMORANDA + ord('0'))
    else:
        current_item_symbol = chr(current_item + ord('A') - 1)

    var_r_local = random_normal(param_R, param_s)
    if var_r_local < 0.1:
        var_r_local = 0.1

    if initial_encoding:
        if distractor:
            encoding_duration = 0.0
        else:
            for j in range(1, NB_ITEM_UNITS + 1):
                item_vectors_in_wm[current_item][j] = item_vectors_in_ltm[current_item][j]

            var_te = logTauE / var_r_local
            if var_te > presentationTime:
                var_te = presentationTime
            encoding_duration = var_te

            if VERBOSE:
                print(f"[{globalTime:.2f}s]   ({distractor}) Encoding duration of {current_item_symbol} = {encoding_duration:1.3f}")

            var_eta = 1 - math.exp(-var_r_local * encoding_duration)
    else:
        if duration == -1:
            var_tr = -math.log(1 - var_tauR) / var_r_local
            if var_tr > time_left:
                var_tr = time_left
            encoding_duration = var_tr
        else:
            encoding_duration = duration

        var_eta = 1 - math.exp(-var_r_local * encoding_duration)
        var_eta /= strength_divisor

    globalTime += encoding_duration

    if (not distractor) and duration == -1:
        apply_decay(item_position_matrix, encoding_duration, current_item)

    if distractor:
        retrieved_item, activation_max, retrieval_duration, _tmp = retrieve(
            position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
            item_position_matrix, item_strength, position, 1
        )

        if param_sameDist == 1:
            if distractorNumber == 0:
                distractorNumber = 1
                create_overlapping_random_pattern(
                    item_vectors_in_ltm[MAX_MEMORANDA + distractorNumber],
                    item_vectors_in_wm[retrieved_item],
                    NB_ITEM_UNITS,
                    param_itemDistractorOverlap,
                )
        else:
            create_overlapping_random_pattern(
                item_vectors_in_ltm[MAX_MEMORANDA + distractorNumber],
                item_vectors_in_wm[retrieved_item],
                NB_ITEM_UNITS,
                param_itemDistractorOverlap,
            )

        for j in range(1, NB_ITEM_UNITS + 1):
            item_vectors_in_wm[MAX_MEMORANDA + distractorNumber][j] = item_vectors_in_ltm[MAX_MEMORANDA + distractorNumber][j]

        if VERBOSE:
            display_item_units(item_vectors_in_wm, MAX_MEMORANDA + distractorNumber)
            display_item_units(item_vectors_in_wm, lastItem)

        interfere(
            item_vectors_in_wm[retrieved_item],
            item_vectors_in_wm[MAX_MEMORANDA + distractorNumber],
            DISTRACTOR_ENCODING_WEIGHT
        )

        if VERBOSE:
            print(f"   {YEL}{name(retrieved_item)} is retrieved at position {position} and altered by the distractor{RESET}")
            display_item_units(item_vectors_in_wm, retrieved_item)

        var_eta *= DISTRACTOR_ENCODING_WEIGHT

    for j in range(1, nbPositionUnits + 1):
        if position_vectors[position][j] != 0:
            item_position_matrix[current_item][j] += (param_L - item_position_matrix[current_item][j]) * var_eta

    if (not initial_encoding) and (not distractor):
        if VERBOSE:
            print(f"   Move WM item {name(best_wm_item)} closer to LTM item {name(current_item)}")
        interfere(item_vectors_in_wm[best_wm_item], item_vectors_in_ltm[current_item], 0.5)
        if VERBOSE:
            display_item_units(item_vectors_in_wm, best_wm_item)

    return encoding_duration


def refresh(position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
            item_position_matrix, item_strength, time_available, last_position):
    current_position = 1
    while time_available > 0:
        afsi = min(param_attentionalFocusSize, last_position)
        cpi = current_position
        reencoding_duration = -1

        while afsi > 0:
            best_ltm_item, activation_max, retrieval_duration, best_wm_item = retrieve(
                position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
                item_position_matrix, item_strength, cpi, 1
            )

            if VERBOSE:
                print(f"   {CYN}It is refreshed.{RESET}")

            reencoding_duration = encode(
                position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
                item_position_matrix, item_strength,
                0, best_ltm_item, best_wm_item, cpi,
                time_available,
                min(param_attentionalFocusSize, last_position),
                reencoding_duration,
                0
            )

            if VERBOSE:
                print(f"   {name(best_ltm_item)} is reencoded in {reencoding_duration:1.3f} ms")

            cpi += 1
            if cpi > last_position:
                cpi = 1
            afsi -= 1

        current_position = cpi
        time_available -= reencoding_duration
        if time_available < 0:
            time_available = 0

    return 0


def processing(position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
               item_position_matrix, item_strength, last_position):
    global var_Rop, var_rop, var_ta, globalTime

    var_Rop = -math.log(1 - param_tauOp) / param_Ta
    var_rop = random_normal(var_Rop, param_s)
    if var_rop < 0.1:
        var_rop = 0.1
    var_ta = -math.log(1 - param_tauOp) / var_rop

    if (var_ta > param_freeTime) and (param_freeTimeIncludesOpDuration == 1):
        if VERBOSE:
            print(f"   Process stopped. Planned to last {var_ta:1.3f} ms but no free time left.")
        var_ta = param_freeTime

    if VERBOSE:
        print(f"[{globalTime:.2f}s]   Processing duration={var_ta:1.3f}")

    encode(
        position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
        item_position_matrix, item_strength,
        1, MAX_MEMORANDA + distractorNumber, -1,
        last_position, 9999, 1, var_ta, 1
    )

    globalTime += var_ta
    apply_decay(item_position_matrix, var_ta, -1)
    return var_ta


def recall(position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
           item_position_matrix, item_strength, last_position):
    global globalTime
    recalled = []

    for position in range(1, last_position + 1):
        best_ltm_item, activation_max, retrieval_duration, best_wm_item = retrieve(
            position_vectors, item_vectors_in_wm, item_vectors_in_ltm,
            item_position_matrix, item_strength, position, 0
        )

        if retrieval_duration > 5:
            retrieval_duration = 5

        apply_decay(item_position_matrix, retrieval_duration, -1)

        if activation_max > param_theta:
            if 1 <= best_ltm_item <= 26:
                code_item = chr(best_ltm_item + ord('A') - 1)
            else:
                code_item = '*'

            for j in range(1, nbPositionUnits + 1):
                if item_vectors_in_wm[best_ltm_item][j] != 0:
                    item_position_matrix[best_ltm_item][j] -= param_L * activation_max
        else:
            code_item = '.'

        if VERBOSE:
            print(f"   {RED}position {position}: {code_item} is retrieved{RESET}")

        recalled.append(code_item)
        globalTime += retrieval_duration

    return "".join(recalled)


def compare_stim_and_recalled(recalled, last_position, res_serial_position_data):
    total_order = 0
    for i in range(last_position):
        if recalled[i] == chr(ord('A') + i):
            total_order += 1
            res_serial_position_data[i + 1] += 1
    return total_order / last_position


def generate_position_representations(position_vectors):
    for i in range(1, nbPositionUnits + 1):
        position_vectors[1][i] = 0

    for i in range(0, NB_UNIT_BLOCKS):
        random_position = 1 + random.randrange(SIZE_OF_POSITION_BLOCKS)
        position_vectors[1][i * SIZE_OF_POSITION_BLOCKS + random_position] = 1

    for p in range(2, MAX_POSITION + 1):
        for i in range(0, NB_UNIT_BLOCKS):
            if random.randrange(100) > param_P * 100:
                for j in range(i * SIZE_OF_POSITION_BLOCKS + 1, (i + 1) * SIZE_OF_POSITION_BLOCKS + 1):
                    position_vectors[p][j] = 0
                random_position = 1 + random.randrange(SIZE_OF_POSITION_BLOCKS)
                position_vectors[p][i * SIZE_OF_POSITION_BLOCKS + random_position] = 1
            else:
                for j in range(i * SIZE_OF_POSITION_BLOCKS + 1, (i + 1) * SIZE_OF_POSITION_BLOCKS + 1):
                    position_vectors[p][j] = position_vectors[p - 1][j]

    if VERBOSE:
        print("POSITION UNITS")
        for p in range(1, MAX_POSITION + 1):
            print(f"   [{p:2d}] ", end="")
            for i in range(1, nbPositionUnits + 1):
                print(position_vectors[p][i], end="")
            print()


def generate_item_representations(item_vectors, d1, d2):
    for i in range(1, MAX_MEMORANDA + 1):
        for j in range(1, NB_ITEM_UNITS + 1):
            item_vectors[i][j] = -1
        create_random_pattern(item_vectors[i], 1, NB_ITEM_UNITS // 4)

    for i in range(MAX_MEMORANDA + 1, MAX_ITEM + 1):
        for j in range(1, NB_ITEM_UNITS + 1):
            item_vectors[i][j] = -1

    if VERBOSE:
        print("ITEM UNITS (first 64 units)")
        for p in range(1, min(26, MAX_MEMORANDA) + 1):
            display_item_units(item_vectors, p)


